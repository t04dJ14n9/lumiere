// Writes THIRD_PARTY_NOTICES.md from the packages esbuild actually bundled
// (artifacts/bundle-inputs.json, written by scripts/build.mjs).
// `--check` fails instead of writing when the file is out of date.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const output = "THIRD_PARTY_NOTICES.md";
const inputs = JSON.parse(readFileSync("artifacts/bundle-inputs.json", "utf8"));
const packageDir = /^(.*node_modules\/(?:@[^/]+\/)?[^/@][^/]*)\//;

function bundledPackages() {
  const dirs = new Map();
  for (const input of inputs) {
    const match = packageDir.exec(input);
    if (!match) {
      continue;
    }
    const dir = match[1];
    const manifest = JSON.parse(
      readFileSync(join(dir, "package.json"), "utf8"),
    );
    dirs.set(`${manifest.name}@${manifest.version}`, { dir, manifest });
  }
  return [...dirs.values()].sort((a, b) =>
    a.manifest.name.localeCompare(b.manifest.name),
  );
}

function licenseText(dir) {
  const file = readdirSync(dir).find((name) =>
    /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i.test(name),
  );
  return file ? readFileSync(join(dir, file), "utf8").trim() : undefined;
}

function licenseName(manifest) {
  if (typeof manifest.license === "string") {
    return manifest.license;
  }
  return manifest.license?.type ?? "see package";
}

function section({ dir, manifest }) {
  const text = licenseText(dir);
  const home =
    manifest.homepage ?? manifest.repository?.url ?? manifest.repository;
  const lines = [
    `## ${manifest.name} ${manifest.version}`,
    "",
    `License: ${licenseName(manifest)}${home ? `  \nSource: ${home}` : ""}`,
    "",
  ];
  if (text) {
    lines.push("```text", text.replaceAll("```", "'''"), "```", "");
  } else {
    lines.push(
      "The package ships no license file; its package.json declares the license above.",
      "",
    );
  }
  return lines.join("\n");
}

const packages = bundledPackages();
const notices = [
  "# Third-party notices",
  "",
  "Markdown Workbench bundles the following packages into `dist/`. Each is",
  "listed with its license as shipped in the package. Generated by",
  "`scripts/third-party-notices.mjs` from the build's bundle inputs.",
  "",
  ...packages.map(section),
].join("\n");

if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current !== notices) {
    console.error(
      `${output} is out of date; run node scripts/third-party-notices.mjs`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(output, notices);
  console.log(`${output}: ${packages.length} packages`);
}
