// Execute the pinned source in a disposable archive, never a source worktree.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, symlinkSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import path from 'node:path';
const commit = 'ff3a902ef4ec50a136455c0cf2ccaff698682a06';
const scratch = mkdtempSync(path.join(tmpdir(), 'mw-ledger-'));
const archive = execFileSync('git', ['-C', path.join(homedir(), 'Code/human-learning'), 'archive', commit, 'packages/markdown-editor', 'packages/vscode-extension/test', 'packages/vscode-extension/src'], { maxBuffer: 100 * 1024 * 1024 });
execFileSync('tar', ['-x', '-C', scratch], { input: archive });
symlinkSync(path.resolve('node_modules'), path.join(scratch, 'node_modules'));
const editor = path.join(scratch, 'packages/markdown-editor');
const executable = name => path.resolve('node_modules/.bin', name);
const evidence = path.resolve('docs/source-test-inventory');
mkdirSync(evidence, { recursive: true });
const rows = [];
// Run per file so every title has an unambiguous source, even repeated titles.
for (const file of readdirSync(path.join(editor, 'test')).filter(p => p.endsWith('.test.ts')).sort()) {
  const output = execFileSync(executable('tsx'), ['--test', '--test-reporter=spec', `test/${file}`], { cwd: editor, encoding: 'utf8', env: { ...process.env, NO_COLOR: '1' } });
  writeFileSync(path.join(evidence, file + '.txt'), output);
  for (const match of output.matchAll(/^[✔✓] (.+?) \([\d.]+m?s\)$/gm)) rows.push(['unit', file, match[1]]);
}
const browser = execFileSync(executable('playwright'), ['test', '--list'], { cwd: editor, encoding: 'utf8' });
writeFileSync(path.join(evidence, 'browser.txt'), browser);
function scenarios(output, tier) {
  for (const match of output.matchAll(/^\s+([^\s]+\.(?:ts|mts)):\d+:\d+ › (.+)$/gm)) rows.push([tier, match[1], match[2]]);
}
scenarios(browser, 'browser');
const native = path.join(scratch, 'native.config.ts');
writeFileSync(native, `export default { testDir: './packages/vscode-extension/test/vscode-e2e', testMatch: ['markdown.spec.ts','properties.spec.ts','file-title.spec.ts','rename-state.spec.ts','obsidian-commands.spec.ts'] };`);
const nativeList = execFileSync(executable('playwright'), ['test', '--list', '--config', native], { cwd: scratch, encoding: 'utf8' });
writeFileSync(path.join(evidence, 'native.txt'), nativeList);
scenarios(nativeList, 'native');
const counts = Object.fromEntries(['unit','browser','native'].map(t => [t, rows.filter(r => r[0] === t).length]));
if (!counts.unit || !counts.browser || !counts.native) throw new Error(`Incomplete inventory ${JSON.stringify(counts)}`);
const ledger = 'docs/TEST_LEDGER.md';
const existing = new Map();
try {
  for (const line of readFileSync(ledger, 'utf8').split('\n')) {
    const cells = line.split(' | ');
    if (cells.length === 4) existing.set(cells.slice(0, 2).join(' | '), cells.slice(2).join(' | '));
  }
} catch { /* First generation. */ }
const escape = s => s.replaceAll('|', '&#124;').replaceAll('\n', ' ');
const lines = rows.map(([tier,file,title]) => {
  const key = `| \`${tier}/${file}\` | ${escape(title)}`;
  return `${key} | ${existing.get(key) ?? 'todo | Awaiting scheduled port |'}`;
});
for (const [key, tail] of existing) if (key.startsWith('| `adapter/')) lines.push(`${key} | ${tail}`);
writeFileSync(ledger, `# Source test ledger\n\nPinned source: \`${commit}\`. Generated by \`pnpm ledger\` using an isolated git archive.\nInventory: ${counts.unit} unit, ${counts.browser} browser, ${counts.native} Markdown native scenarios.\nRaw source runner output: [source-test-inventory](source-test-inventory/).\n\n| Source | Title | Status | Destination or reason |\n| --- | --- | --- | --- |\n${lines.join('\n')}\n`);
console.log(JSON.stringify({ scratch, counts, total: rows.length }));
