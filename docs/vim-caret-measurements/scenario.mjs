// The key sequence both measurements run: one shot per caret state.
export async function scenario({ page, shot, keys }) {
  await shot("normal-line-start");
  await keys("w");
  await shot("normal-word");
  await keys("$");
  await shot("normal-line-end");
  await keys("j");
  await shot("normal-empty-line");
  await keys("j");
  await keys("$");
  await shot("normal-short-line-end");
  await keys("j");
  await keys("0");
  await keys("fw");
  await keys("l".repeat(6));
  await shot("normal-cjk");
  await keys("l");
  await shot("normal-cjk-2nd");
  await keys("0");
  await keys("fm");
  await keys("h");
  await shot("normal-accent");
  await keys("0");
  await keys("fj");
  await keys("lll");
  await shot("normal-emoji");
  await keys("l");
  await shot("normal-after-emoji");
  await keys("h");
  await keys("h");
  await shot("normal-back-over-emoji");
  await keys("0");
  await shot("normal-wide-line-start");
  await keys("j0");
  await keys("l");
  await shot("normal-combining");
  // Insert and Esc
  await keys("gg0");
  await keys("ww");
  await shot("normal-before-insert");
  await keys("i");
  await shot("insert");
  await page.keyboard.press("Escape");
  await shot("normal-after-esc-from-insert");
  await keys("a");
  await shot("insert-after-a");
  await page.keyboard.press("Escape");
  await shot("normal-after-esc-from-a");
  await keys("A");
  await shot("insert-at-line-end");
  await page.keyboard.press("Escape");
  await shot("normal-after-esc-from-A");
  await keys("R");
  await shot("replace");
  await page.keyboard.press("Escape");
  await shot("normal-after-esc-from-R");
  await keys("0r");
  await shot("pending-r");
  await page.keyboard.press("Escape");
  await keys("d");
  await page.waitForTimeout(900);
  await shot("operator-pending");
  await page.keyboard.press("Escape");
  // Visual modes
  await keys("0");
  await keys("v");
  await shot("visual-empty");
  await keys("lll");
  await shot("visual-forward");
  await keys("hhhhh");
  await shot("visual-backward");
  await page.keyboard.press("Escape");
  await shot("normal-after-visual");
  await keys("Vj");
  await shot("visual-line");
  await page.keyboard.press("Escape");
  await page.keyboard.press("Control+v");
  await keys("lljj");
  await shot("visual-block");
  await page.keyboard.press("Escape");
  await keys("gg0");
  await keys("/line");
  await shot("search-in-progress");
  await page.keyboard.press("Escape");
  await keys("gg0:");
  await shot("commandline");
  await page.keyboard.press("Escape");
}
